export type TKey = keyof (typeof dict)["en"];

type I18nCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  tl: (k: TKey) => readonly string[];
};

const Ctx = createContext<I18nCtx>({
  lang: "uz",
  setLang: () => {},
  t: (k) => dict.en[k] as string,
  tl: (k) => dict.en[k] as unknown as readonly string[],
});

export function I18nProvider({
  lang,
  setLang,
  children,
}: {
  lang: Lang;
  setLang: (l: Lang) => void;
  children: ReactNode;
}) {
  const t = (k: TKey) => dict[lang][k] as string;
  const tl = (k: TKey) => dict[lang][k] as unknown as readonly string[];
  return <Ctx.Provider value={{ lang, setLang, t, tl }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
